"""The reference pages generated from the models and the parser."""

# ruff: noqa: SLF001  # argparse has no public way to list a parser's arguments and subcommands

import argparse
import types
from typing import Annotated, Union, get_args, get_origin

from pydantic import BaseModel

from code_factory.settings.models.kinds import Kind
from code_factory.settings.models.modules import ColumnFacts, ModuleFacts, TableFacts

_SKIPPED = (
    argparse._HelpAction,
    argparse._VersionAction,
    argparse._SubParsersAction,
)
_HEADER = (
    "# Config settings\n\nThe tables of `.code-factory/config.toml` that "
    "`code-factory config check` knows.\nGenerated by `code-factory docs`; do not edit by hand.\n"
)


def _members(annotation: object) -> list[object]:
    if get_origin(annotation) in {Union, types.UnionType}:
        return list(get_args(annotation))
    return [annotation]


def _words(annotation: object) -> str:
    """What a field's kind says it takes."""
    for member in _members(annotation):
        if get_origin(member) is Annotated:
            for meta in member.__metadata__:  # ty: ignore[missing-attribute]  # Annotated
                if isinstance(meta, Kind):
                    return meta.words
    msg = f"a field without a kind: {annotation!r}"
    raise TypeError(msg)


def _table_of(annotation: object) -> tuple[type[BaseModel], bool] | None:
    """The model a field holds, and whether it is a list of them."""
    for member in _members(annotation):
        if isinstance(member, type) and issubclass(member, BaseModel):
            return member, False
        if get_origin(member) is list:
            (item,) = get_args(member)
            if isinstance(item, type) and issubclass(item, BaseModel):
                return item, True
    return None


def render_config_page(model: type[BaseModel]) -> str:
    """One section per table and list of tables of `model`, each key with what it takes."""
    page = _HEADER
    for name, field in model.model_fields.items():
        found = _table_of(field.annotation)
        if found is None:
            continue
        table, is_list = found
        page += f"\n## [[{name}]]\n\n" if is_list else f"\n## [{name}]\n\n"
        page += "".join(
            f"- `{key}`: {_words(item.annotation)}\n" for key, item in table.model_fields.items()
        )
    return page


def _help(action: argparse.Action) -> str:
    text = action.help or ""
    if "%" not in text:
        return text
    return text % {**vars(action), "prog": ""}


def _argument(action: argparse.Action) -> str | None:
    if isinstance(action, _SKIPPED) or action.help == argparse.SUPPRESS:
        return None
    longs = [s for s in action.option_strings if s.startswith("--")]
    name = (
        longs[0]
        if longs
        else (action.option_strings[0] if action.option_strings else f"<{action.dest}>")
    )
    help_text = _help(action)
    return f"- `{name}`: {help_text}" if help_text else f"- `{name}`"


def _sections(parser: argparse.ArgumentParser, path: str, about: str) -> str:
    text = f"\n## {path}\n"
    if about:
        text += f"\n{about}\n"
    arguments = [line for a in parser._actions if (line := _argument(a)) is not None]
    if arguments:
        text += "\n" + "\n".join(arguments) + "\n"
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            helps = {c.dest: c.help for c in action._choices_actions}
            for name, sub in action.choices.items():
                if helps.get(name) == argparse.SUPPRESS:
                    continue
                text += _sections(sub, f"{path} {name}", helps.get(name) or sub.description or "")
    return text


def render_commands_page(parser: argparse.ArgumentParser) -> str:
    """One section per command and subcommand, depth first in the parser's order.

    Each has its path, its description and each argument with its help; hidden commands
    (`help=argparse.SUPPRESS`), `-h` and `--version` are left out.
    """
    return "# Commands\n\nGenerated by `code-factory docs`; do not edit by hand.\n" + _sections(
        parser, parser.prog, parser.description or ""
    )


def _cell(items: tuple[str, ...]) -> str:
    return "<br>".join(f"`{item}`" for item in items) if items else ""


def render_modules_page(modules: list[ModuleFacts]) -> str:
    """One row per module in the order the app builds them, and its routes, commands and tables."""
    lines = [
        "# Modules",
        "",
        "Generated by `code-factory docs` from `app.MODULES`; do not edit by hand. A module is",
        "listed after the modules it reads. The MCP tools each caller sees are pinned in",
        "`tests/golden/mcp/`.",
        "",
        "| Module | What it is | Commands | MCP | Background | Tables |",
        "|---|---|---|---|---|---|",
    ]
    lines.extend(
        f"| `{module.name}` | {module.summary} | "
        f"{_cell(tuple(command.name for command in module.commands))} | "
        f"{'tools' if module.tools else ''} | {'yes' if module.background else ''} | "
        f"{_cell(module.tables)} |"
        for module in modules
    )
    for module in modules:
        if module.routes:
            lines += ["", f"## {module.name}", "", *(f"- `{route}`" for route in module.routes)]
    return "\n".join(lines) + "\n"


def _branch(items: list[tuple[str, list[str]]], indent: str) -> list[str]:
    """Each item as a tree line under `indent`, its children nested one level deeper."""
    lines: list[str] = []
    for index, (text, children) in enumerate(items):
        last = index == len(items) - 1
        lines.append(f"{indent}{'└── ' if last else '├── '}{text}")
        lines += _branch([(child, []) for child in children], indent + ("    " if last else "│   "))
    return lines


def _module_branches(module: ModuleFacts) -> list[tuple[str, list[str]]]:
    branches: list[tuple[str, list[str]]] = []
    if module.commands:
        commands = [f"{command.name}: {command.help}" for command in module.commands]
        branches.append(("commands", commands))
    if module.tools:
        branches.append(("MCP tools (each caller's list is in tests/golden/mcp/)", []))
    if module.background:
        branches.append(("background work, started with the served app", []))
    if module.tables:
        branches.append(("tables", list(module.tables)))
    if module.routes:
        branches.append(("routes", list(module.routes)))
    return branches


def render_feature_map_page(modules: list[ModuleFacts]) -> str:
    """Every module as a tree, in the order the app builds them, with what it serves and stores."""
    lines = [
        "# Feature map",
        "",
        "Generated by `code-factory docs` from `app.MODULES`; do not edit by hand. Each module",
        "with its commands, MCP tools, background work, tables and routes. What a module does",
        "and why is in its own page, listed in the README's Documentation table.",
        "",
        "```text",
        "code-factory",
        "│",
    ]
    for index, module in enumerate(modules):
        last = index == len(modules) - 1
        lines.append(f"{'└── ' if last else '├── '}{module.name}: {module.summary}")
        lines += _branch(_module_branches(module), "    " if last else "│   ")
    lines.append("```")
    return "\n".join(lines) + "\n"


def _key(column: ColumnFacts) -> str:
    keys = (["primary key"] if column.primary_key else []) + [
        f"`{target}`" for target in column.references
    ]
    return ", ".join(keys)


def _column_row(column: ColumnFacts) -> str:
    default = column.default if column.default in {"", "identity"} else f"`{column.default}`"
    null = "yes" if column.nullable else "no"
    return f"| `{column.name}` | `{column.type}` | {null} | {default} | {_key(column)} |"


def render_tables_page(tables: list[TableFacts]) -> str:
    """Every table under the module that owns it, in the order the app builds the modules."""
    lines = [
        "# Database tables",
        "",
        "Generated by `code-factory docs` from the tables on `platform.db.Base`; do not edit by",
        "hand. Defaults are the database's own; a key is the primary key or the column a foreign",
        "key references. Indexes and check constraints are in each module's `tables.py`.",
    ]
    module = ""
    for table in tables:
        if table.module != module:
            module = table.module
            lines += ["", f"## {module}"]
        lines += ["", f"### {table.name}", ""]
        if table.summary:
            lines += [table.summary, ""]
        lines += ["| Column | Type | Null | Default | Key |", "|---|---|---|---|---|"]
        lines += [_column_row(column) for column in table.columns]
    return "\n".join(lines) + "\n"

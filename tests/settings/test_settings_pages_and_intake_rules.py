"""The generated reference pages and the intake key check. The commands page cases are worked by
hand from the previous implementation's `docs.rs` and `reference_docs.rs` behaviour."""

import argparse

from code_factory.settings.models.config import RepositoryConfig
from code_factory.settings.models.problems import IntakeGrant
from code_factory.settings.rules import (
    grant_serves,
    intake_key_problems,
    lenient_config,
    render_commands_page,
    render_config_page,
    ticket_prefix,
)

CONFIG = (
    '[intake]\njira_url = "https://acme.atlassian.net"\njira_jql = "project = ENG"\n'
    'jira_email = "bot@acme.example"\njira_token_env = "CODE_FACTORY_INTAKE_JIRA"\n'
    'linear_label = "x"\nlinear_token_env = "CODE_FACTORY_INTAKE_LINEAR"\n'
)
LINEAR = IntakeGrant(
    key_name="CODE_FACTORY_INTAKE_LINEAR",
    repository="/work/repo",
    url="https://api.linear.app/graphql",
)


def jira(repository: str, url: str) -> IntakeGrant:
    return IntakeGrant(key_name="CODE_FACTORY_INTAKE_JIRA", repository=repository, url=url)


def problems(grants: list[IntakeGrant]) -> list[tuple[int, str]]:
    found = intake_key_problems(
        lenient_config(CONFIG), CONFIG, {g.key_name: g for g in grants}, "/work/repo"
    )
    assert {p.path for p in found} <= {".code-factory/config.toml"}
    return [(p.line, p.message) for p in found]


def test_a_key_held_for_another_repository_is_named_on_its_line() -> None:
    assert problems([jira("/elsewhere/victim", "https://acme.atlassian.net"), LINEAR]) == [
        (
            5,
            (
                "intake.jira_token_env: CODE_FACTORY_INTAKE_JIRA is held on this machine for "
                "/elsewhere/victim at https://acme.atlassian.net"
            ),
        )
    ]


def test_a_key_held_for_another_site_is_named() -> None:
    assert problems([jira("/work/repo", "https://victim.atlassian.net"), LINEAR]) == [
        (
            5,
            (
                "intake.jira_token_env: CODE_FACTORY_INTAKE_JIRA is held on this machine for "
                "/work/repo at https://victim.atlassian.net"
            ),
        )
    ]


def test_a_key_held_for_this_repository_and_address_passes_with_or_without_a_slash() -> None:
    assert problems([jira("/work/repo", "https://acme.atlassian.net/"), LINEAR]) == []
    assert problems([jira("/work/repo", "https://acme.atlassian.net"), LINEAR]) == []


def test_linear_without_an_address_is_held_to_the_linear_api() -> None:
    wrong = LINEAR.model_copy(update={"url": "https://localhost:1/graphql"})
    found = problems([jira("/work/repo", "https://acme.atlassian.net"), wrong])
    assert [line for line, _ in found] == [7]


def test_a_key_with_no_grant_is_no_problem() -> None:
    assert problems([]) == []


def test_a_grant_serves_the_same_repository_text_and_address_up_to_a_trailing_slash() -> None:
    grant = jira("/work/repo", "https://acme.atlassian.net/")
    assert grant_serves(grant, "/work/repo", "https://acme.atlassian.net")
    assert not grant_serves(grant, "/work/repo/", "https://acme.atlassian.net")
    assert not grant_serves(grant, "/work/repo", "https://acme.atlassian.net.evil.com")


def test_the_ticket_prefix_is_the_valid_setting_or_cf() -> None:
    assert ticket_prefix(lenient_config("")) == "CF"
    assert ticket_prefix(lenient_config('[tickets]\nprefix = "ENG"\n')) == "ENG"
    assert ticket_prefix(lenient_config('[tickets]\nprefix = "eng"\n')) == "CF"
    assert ticket_prefix(lenient_config('[tickets]\nprefix = "ABCDEFGHIJK"\n')) == "CF"


def test_the_config_page_lists_every_table_and_key_with_its_wording() -> None:
    page = render_config_page(RepositoryConfig)
    assert page.startswith(
        "# Config settings\n\nThe tables of `.code-factory/config.toml` that "
        "`code-factory config check` knows.\nGenerated by `code-factory docs`; do not edit by "
        "hand.\n\n## [checks]\n\n- `command`: text, not empty\n"
    )
    lines = page.splitlines()
    for expected in (
        "## [agents]",
        "## [[recurring]]",
        "- `review`: true or false",
        "- `judge_sample`: a whole number from 1 to 50",
        "- `judge_share`: a number above 0 and at most 0.2",
        "- `prefix`: 1 to 10 capital letters or digits, a letter first",
    ):
        assert expected in lines
    assert "## [board]" not in lines
    assert "- `file_after`: a positive integer" not in lines
    assert page.endswith("- `threshold`: a positive integer\n")


def parser() -> argparse.ArgumentParser:
    root = argparse.ArgumentParser(prog="tool", description="the tool")
    root.add_argument("--version", action="version", version="tool 1")
    commands = root.add_subparsers(dest="command", required=True)
    serve = commands.add_parser("serve", help="serve it")
    serve.add_argument("--port", type=int, help="the port")
    serve.add_argument("--quiet", action="store_true")
    config = commands.add_parser("config", help="check the config")
    config.add_argument("action", choices=["check", "show"])
    config.add_argument("path", nargs="?", help="the repository")
    commands.add_parser("secret", help=argparse.SUPPRESS)
    db = commands.add_parser("db", help="database commands").add_subparsers(dest="db_command")
    db.add_parser("upgrade", help="migrate").add_argument("--to", help="a revision")
    return root


def test_the_commands_page_has_a_section_per_command_depth_first_with_each_option() -> None:
    assert render_commands_page(parser()) == (
        "# Commands\n\nGenerated by `code-factory docs`; do not edit by hand.\n"
        "\n## tool\n\nthe tool\n"
        "\n## tool serve\n\nserve it\n\n- `--port`: the port\n- `--quiet`\n"
        "\n## tool config\n\ncheck the config\n\n- `<action>`\n- `<path>`: the repository\n"
        "\n## tool db\n\ndatabase commands\n"
        "\n## tool db upgrade\n\nmigrate\n\n- `--to`: a revision\n"
    )


def test_a_hidden_command_help_and_version_are_left_out() -> None:
    page = render_commands_page(parser())
    for absent in ("secret", "--help", "-h", "--version"):
        assert absent not in page
